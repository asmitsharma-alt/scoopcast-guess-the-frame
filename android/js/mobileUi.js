  async share() {
    if (!this._currentCanvas || !this._currentBlob) {
      await this.generateCanvas(this._currentPlayers);
    }
    const blob = this._currentBlob;

    try {
      if (blob) {
        const file = new File([blob], 'scoopcast-winner-scorecard.png', { type: 'image/png' });
        const shareData = {
          title: 'Guess The Frame - Match Result 🎬🍿',
          text: 'Check out who won Guess The Frame! 🎬🍿 Think you know your movies? Play free online at: https://scoopcast.me',
          url: 'https://scoopcast.me'
        };

        if (navigator.canShare && navigator.canShare({ files: [file] })) {
          try {
            await navigator.share({ ...shareData, files: [file] });
            if (typeof UI !== 'undefined' && UI.showToast) UI.showToast('🎉 Shared successfully!');
            return;
          } catch (err) {
            if (err.name === 'AbortError') return;
          }
        }

        if (navigator.share) {
          try {
            await navigator.share(shareData);
            this.download();
            return;
          } catch (err) {
            if (err.name === 'AbortError') return;
          }
        }
      }
      this.fallbackShare();
    } catch (err) {
      this.fallbackShare();
    }
  },

  async copy() {
    if (!this._currentCanvas || !this._currentBlob) {
      await this.generateCanvas(this._currentPlayers);
    }
    if (this._currentBlob && navigator.clipboard && navigator.clipboard.write) {
      try {
        await navigator.clipboard.write([
          new ClipboardItem({ 'image/png': this._currentBlob })
        ]);
        if (typeof UI !== 'undefined' && UI.showToast) {
          UI.showToast('📋 Image copied to clipboard!');
        } else {
          alert('📋 Image copied to clipboard!');
        }
        return;
      } catch (err) {
        console.warn('Clipboard write failed:', err);
      }
    }
    this.fallbackShare();
  },

  download() {
    if (!this._currentCanvas && !this._currentDataUrl) {
      this.generateCanvas(this._currentPlayers);
    }
    const dataUrl = this._currentDataUrl || (this._currentCanvas ? this._currentCanvas.toDataURL('image/png') : null);
    if (!dataUrl) return;

    const link = document.createElement('a');
    link.href = dataUrl;
    link.download = 'scoopcast-winner-scorecard.png';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    if (typeof UI !== 'undefined' && UI.showToast) {
      UI.showToast('✅ Scorecard image saved!');
    }
  },

  fallbackShare() {
    const shareText = '🎬 Guess The Frame - Match Scorecard 🍿\nPlay free online: https://scoopcast.me';
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(shareText);
    }
    this.download();
    if (typeof UI !== 'undefined' && UI.showToast) {
      UI.showToast('📋 Link copied & scorecard image downloaded!');
    }
  }
