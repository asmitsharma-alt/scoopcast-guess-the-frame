function resolveMediaPath(src) {
  if (!src) return '';
  if (src.startsWith('http://') || src.startsWith('https://')) {
    let url = src;
    if (url.includes('res.cloudinary.com') && url.includes('/upload/') && !url.includes('/upload/f_auto,q_auto/') && !url.endsWith('.svg')) {
      url = url.replace('/upload/', '/upload/f_auto,q_auto/');
    }
    return url;
  }
  let path = src.startsWith('/') ? src : '/' + src;
  if (path.startsWith('/tie breaker/')) {
    path = path.replace('/tie breaker/', '/tie_breaker/');
  }
  return path;
}

